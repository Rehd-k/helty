import 'dart:typed_data';

import 'package:flutter/services.dart' show rootBundle;
import 'package:helty/src/app/org_config.dart';
import 'package:pdf/widgets.dart' as pw;

/// 1×1 transparent PNG. Stand-in when [OrgConfig.logoAsset] is unset so
/// letterhead keeps its layout without substituting another hospital's mark.
final Uint8List _transparentPng = Uint8List.fromList(const <int>[
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D,
  0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
  0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00,
  0x0A, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00,
  0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49,
  0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
]);

/// Logo for PDF letterhead. A missing [OrgConfig.logoAsset] yields a blank image.
Future<pw.ImageProvider> loadOrgPdfLogo() async {
  final path = OrgConfig.instance.logoAsset.trim();
  if (path.isEmpty) return pw.MemoryImage(_transparentPng);
  final data = await rootBundle.load(path);
  return pw.MemoryImage(data.buffer.asUint8List());
}
